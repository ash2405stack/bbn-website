// Writes docs/OPEN-ITEMS.md from site/js/register.js (the single editable register).
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadBBN, root } from './load-data.mjs';
const reg = loadBBN().register;
const cell = s => String(s || '').replace(/\|/g, '/');
let md = `# BBN website: open-item register\n\nGenerated from \`site/js/register.js\`. Do not edit this file. Edit the register and run \`node tools/export-register.mjs\`.\n\n${reg.length} items. ${reg.filter(r => r.status === 'Confirmed').length} confirmed.\n\n| Placeholder key | Q no. | What is needed | Owner | Status | Source | Affected pages |\n|---|---|---|---|---|---|---|\n`;
for (const r of reg) md += `| \`${r.key}\` | ${r.q || 'Not mapped'} | ${cell(r.field)} | ${cell(r.owner)} | ${cell(r.status)} | ${cell(r.source)} | ${cell(r.pages)} |\n`;
writeFileSync(join(root, 'docs/OPEN-ITEMS.md'), md);
console.log(`docs/OPEN-ITEMS.md written (${reg.length} items)`);
